alter table public.profiles
  add column if not exists avatar_url text;

alter table public.listings
  add column if not exists owner_id uuid references auth.users(id) on delete cascade,
  add column if not exists is_available boolean not null default true,
  add column if not exists created_at timestamptz not null default now();

create index if not exists listings_owner_id_idx on public.listings(owner_id);

create table if not exists public.roommate_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  heading text not null,
  budget text not null,
  description text not null default '',
  location text not null,
  role text not null,
  author_name text,
  author_avatar_url text,
  author_gender text,
  author_age integer,
  created_at timestamptz not null default now()
);

alter table public.roommate_posts
  add column if not exists author_avatar_url text;

create index if not exists roommate_posts_created_at_idx
  on public.roommate_posts(created_at desc);
create index if not exists roommate_posts_user_id_idx
  on public.roommate_posts(user_id);

alter table public.listings enable row level security;
alter table public.roommate_posts enable row level security;
alter table public.profiles enable row level security;

drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Users can update their roommate posts" on public.roommate_posts;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'profiles'
      and policyname = 'Users can view their own profile'
  ) then
    create policy "Users can view their own profile"
      on public.profiles for select to authenticated
      using (id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'profiles'
      and policyname = 'Users can insert their own profile'
  ) then
    create policy "Users can insert their own profile"
      on public.profiles for insert to authenticated
      with check (id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'profiles'
      and policyname = 'Users can update their own profile'
  ) then
    create policy "Users can update their own profile"
      on public.profiles for update to authenticated
      using (id = auth.uid())
      with check (id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'listings'
      and policyname = 'Authenticated users can view available listings'
  ) then
    create policy "Authenticated users can view available listings"
      on public.listings for select to authenticated
      using (is_available);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'listings'
      and policyname = 'Owners can view their listings'
  ) then
    create policy "Owners can view their listings"
      on public.listings for select to authenticated
      using (owner_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'listings'
      and policyname = 'Owners can insert their listings'
  ) then
    create policy "Owners can insert their listings"
      on public.listings for insert to authenticated
      with check (
        owner_id = auth.uid()
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('OWNER', 'LANDLORD')
        )
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'listings'
      and policyname = 'Owners can update their listings'
  ) then
    create policy "Owners can update their listings"
      on public.listings for update to authenticated
      using (
        owner_id = auth.uid()
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('OWNER', 'LANDLORD')
        )
      )
      with check (
        owner_id = auth.uid()
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('OWNER', 'LANDLORD')
        )
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'roommate_posts'
      and policyname = 'Authenticated users can view roommate posts'
  ) then
    create policy "Authenticated users can view roommate posts"
      on public.roommate_posts for select to authenticated
      using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'roommate_posts'
      and policyname = 'Users can create their roommate posts'
  ) then
    create policy "Users can create their roommate posts"
      on public.roommate_posts for insert to authenticated
      with check (
        user_id = auth.uid()
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('RENTER', 'USER')
        )
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'roommate_posts'
      and policyname = 'Users can update their roommate posts'
  ) then
    create policy "Users can update their roommate posts"
      on public.roommate_posts for update to authenticated
      using (
        user_id = auth.uid()
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('RENTER', 'USER')
        )
      )
      with check (
        user_id = auth.uid()
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('RENTER', 'USER')
        )
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'roommate_posts'
      and policyname = 'Users can delete their roommate posts'
  ) then
    create policy "Users can delete their roommate posts"
      on public.roommate_posts for delete to authenticated
      using (
        user_id = auth.uid()
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('RENTER', 'USER')
        )
      );
  end if;
end
$$;

insert into storage.buckets (id, name, public)
values ('profile-photos', 'profile-photos', true), ('listing-photos', 'listing-photos', true)
on conflict (id) do update set public = excluded.public;

drop policy if exists "Users can upload their profile photos" on storage.objects;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'Users can upload their profile photos'
  ) then
    create policy "Users can upload their profile photos"
      on storage.objects for insert to authenticated
      with check (
        bucket_id = 'profile-photos'
        and (storage.foldername(name))[1] = auth.uid()::text
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'Users can update their profile photos'
  ) then
    create policy "Users can update their profile photos"
      on storage.objects for update to authenticated
      using (
        bucket_id = 'profile-photos'
        and (storage.foldername(name))[1] = auth.uid()::text
      )
      with check (
        bucket_id = 'profile-photos'
        and (storage.foldername(name))[1] = auth.uid()::text
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'Users can upload their listing photos'
  ) then
    create policy "Users can upload their listing photos"
      on storage.objects for insert to authenticated
      with check (
        bucket_id = 'listing-photos'
        and (storage.foldername(name))[1] = auth.uid()::text
        and exists (
          select 1 from public.profiles
          where profiles.id = auth.uid() and upper(profiles.role::text) in ('OWNER', 'LANDLORD')
        )
      );
  end if;
end
$$;
