create table if not exists public.activity_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists activity_history_user_created_idx
  on public.activity_history(user_id, created_at desc);

alter table public.activity_history enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'activity_history'
      and policyname = 'Users can view their activity history'
  ) then
    create policy "Users can view their activity history"
      on public.activity_history for select to authenticated
      using (user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'activity_history'
      and policyname = 'Users can record their activity'
  ) then
    create policy "Users can record their activity"
      on public.activity_history for insert to authenticated
      with check (user_id = auth.uid());
  end if;
end
$$;

