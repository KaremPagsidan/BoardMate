create table if not exists public.profile_photo_gallery (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  photo_url text not null,
  created_at timestamptz not null default now(),
  unique (user_id, photo_url)
);

create index if not exists profile_photo_gallery_user_created_idx
  on public.profile_photo_gallery(user_id, created_at desc);

alter table public.profile_photo_gallery enable row level security;

grant select, insert on public.profile_photo_gallery to authenticated;
grant usage, select on sequence public.profile_photo_gallery_id_seq to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'profile_photo_gallery'
      and policyname = 'Users can view their profile photo gallery'
  ) then
    create policy "Users can view their profile photo gallery"
      on public.profile_photo_gallery for select to authenticated
      using (user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'profile_photo_gallery'
      and policyname = 'Users can add to their profile photo gallery'
  ) then
    create policy "Users can add to their profile photo gallery"
      on public.profile_photo_gallery for insert to authenticated
      with check (user_id = auth.uid());
  end if;
end
$$;

insert into public.profile_photo_gallery (user_id, photo_url)
select id, avatar_url
from public.profiles
where avatar_url is not null
on conflict (user_id, photo_url) do nothing;

notify pgrst, 'reload schema';
