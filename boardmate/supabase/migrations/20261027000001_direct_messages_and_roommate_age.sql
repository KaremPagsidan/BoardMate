alter table public.roommate_posts
  add column if not exists author_age integer;

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint direct_messages_distinct_participants check (sender_id <> recipient_id)
);

create index if not exists direct_messages_sender_created_idx
  on public.direct_messages(sender_id, created_at desc);
create index if not exists direct_messages_recipient_created_idx
  on public.direct_messages(recipient_id, created_at desc);

alter table public.direct_messages enable row level security;
revoke all on public.direct_messages from public, anon, authenticated;
grant select, insert on public.direct_messages to authenticated;
grant usage, select on sequence public.direct_messages_id_seq to authenticated;

drop policy if exists "Participants can view their direct messages" on public.direct_messages;
create policy "Participants can view their direct messages"
  on public.direct_messages for select to authenticated
  using (
    (sender_id = (select auth.uid()) or recipient_id = (select auth.uid()))
    and (select public.is_boardmate_account_approved((select auth.uid())))
  );

drop policy if exists "Approved users can send direct messages" on public.direct_messages;
create policy "Approved users can send direct messages"
  on public.direct_messages for insert to authenticated
  with check (
    sender_id = (select auth.uid())
    and recipient_id <> (select auth.uid())
    and (select public.is_boardmate_account_approved((select auth.uid())))
    and (select public.is_boardmate_account_approved(recipient_id))
  );

create or replace function public.get_boardmate_message_contacts()
returns table (user_id uuid, full_name text, avatar_url text)
language sql
stable
security definer
set search_path = ''
as $$
  select distinct
    profile.id,
    profile.full_name,
    profile.avatar_url
  from public.profiles as profile
  join public.direct_messages as dm
    on profile.id = case
      when dm.sender_id = (select auth.uid()) then dm.recipient_id
      else dm.sender_id
    end
  where (dm.sender_id = (select auth.uid()) or dm.recipient_id = (select auth.uid()))
    and (select public.is_boardmate_account_approved((select auth.uid())))
    and profile.verification_status = 'approved';
$$;

revoke all on function public.get_boardmate_message_contacts() from public;
grant execute on function public.get_boardmate_message_contacts() to authenticated;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'direct_messages'
    ) then
    alter publication supabase_realtime add table public.direct_messages;
  end if;
end
$$;

notify pgrst, 'reload schema';
