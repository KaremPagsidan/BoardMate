create table if not exists public.admin_review_notifications (
  id bigint generated by default as identity primary key,
  notification_key text not null unique,
  title text not null,
  detail text not null,
  destination_tab text not null check (destination_tab in ('verifications', 'listings', 'roommates', 'safety')),
  icon text not null,
  source_type text not null check (source_type in ('profile', 'listing', 'roommate_post', 'message_report')),
  source_id text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  hidden_until timestamptz
);

create index if not exists admin_review_notifications_created_idx
  on public.admin_review_notifications(created_at desc);

alter table public.admin_review_notifications enable row level security;
revoke all on public.admin_review_notifications from public, anon, authenticated;
grant select, delete on public.admin_review_notifications to authenticated;
grant update (read_at, hidden_until) on public.admin_review_notifications to authenticated;

drop policy if exists "Admins can view review notifications" on public.admin_review_notifications;
create policy "Admins can view review notifications"
  on public.admin_review_notifications for select to authenticated
  using ((select public.is_boardmate_admin()));

drop policy if exists "Admins can update review notifications" on public.admin_review_notifications;
create policy "Admins can update review notifications"
  on public.admin_review_notifications for update to authenticated
  using ((select public.is_boardmate_admin()))
  with check ((select public.is_boardmate_admin()));

drop policy if exists "Admins can delete review notifications" on public.admin_review_notifications;
create policy "Admins can delete review notifications"
  on public.admin_review_notifications for delete to authenticated
  using ((select public.is_boardmate_admin()));

create or replace function public.enqueue_admin_review_notification()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  row_data jsonb := pg_catalog.to_jsonb(new);
  item_id text := row_data ->> 'id';
  notification_title text;
  notification_detail text;
  destination text;
  notification_icon text;
  item_status text;
begin
  if tg_table_name = 'profiles' then
    item_status := row_data ->> 'verification_status';
    if item_status <> 'pending' then
      return new;
    end if;
    notification_title := case
      when upper(coalesce(row_data ->> 'role', '')) in ('OWNER', 'LANDLORD')
        then 'Owner verification needs review'
      else 'User verification needs review'
    end;
    notification_detail := coalesce(nullif(row_data ->> 'full_name', ''), nullif(row_data ->> 'email', ''), 'Name not provided');
    destination := 'verifications';
    notification_icon := case
      when upper(coalesce(row_data ->> 'role', '')) in ('OWNER', 'LANDLORD') then '🏠'
      else '👤'
    end;
  elsif tg_table_name = 'listings' then
    item_status := row_data ->> 'moderation_status';
    if item_status <> 'pending' then
      return new;
    end if;
    notification_title := 'Accommodation listing needs review';
    notification_detail := coalesce(nullif(row_data ->> 'title', ''), 'Untitled listing');
    destination := 'listings';
    notification_icon := '🏢';
  elsif tg_table_name = 'roommate_posts' then
    item_status := row_data ->> 'moderation_status';
    if item_status <> 'pending' then
      return new;
    end if;
    notification_title := 'Roommate post needs review';
    notification_detail := coalesce(nullif(row_data ->> 'heading', ''), nullif(row_data ->> 'author_name', ''), 'Untitled post');
    destination := 'roommates';
    notification_icon := '👥';
  elsif tg_table_name = 'direct_message_reports' then
    item_status := row_data ->> 'status';
    if item_status <> 'open' then
      return new;
    end if;
    notification_title := 'Flagged conversation report';
    select pg_catalog.format(
      '%s reported %s',
      coalesce(nullif(reporter.full_name, ''), 'BoardMate member'),
      coalesce(nullif(reported.full_name, ''), 'a user')
    )
    into notification_detail
    from public.profiles reporter
    join public.profiles reported on reported.id = (row_data ->> 'reported_user_id')::uuid
    where reporter.id = (row_data ->> 'reporter_id')::uuid;
    notification_detail := coalesce(notification_detail, 'A conversation was reported for review.');
    destination := 'safety';
    notification_icon := '🛡️';
  else
    return new;
  end if;

  insert into public.admin_review_notifications (
    notification_key, title, detail, destination_tab, icon, source_type, source_id, created_at
  )
  values (
    tg_table_name || ':' || item_id,
    notification_title,
    notification_detail,
    destination,
    notification_icon,
    case tg_table_name
      when 'profiles' then 'profile'
      when 'listings' then 'listing'
      when 'roommate_posts' then 'roommate_post'
      else 'message_report'
    end,
    item_id,
    coalesce((row_data ->> 'created_at')::timestamptz, pg_catalog.now())
  )
  on conflict (notification_key) do nothing;

  return new;
end;
$$;

create or replace function public.mark_admin_review_notification_reviewed()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  item_id text := pg_catalog.to_jsonb(new) ->> 'id';
  source_name text := tg_table_name;
begin
  if tg_table_name = 'profiles' then
    source_name := 'profiles';
  elsif tg_table_name = 'listings' then
    source_name := 'listings';
  elsif tg_table_name = 'roommate_posts' then
    source_name := 'roommate_posts';
  elsif tg_table_name = 'direct_message_reports' then
    source_name := 'direct_message_reports';
  end if;

  update public.admin_review_notifications
  set read_at = coalesce(read_at, pg_catalog.now()),
      title = pg_catalog.regexp_replace(title, 'needs review$', 'reviewed')
  where notification_key = source_name || ':' || item_id;

  return new;
end;
$$;

revoke all on function public.enqueue_admin_review_notification() from public, anon, authenticated;
revoke all on function public.mark_admin_review_notification_reviewed() from public, anon, authenticated;

drop trigger if exists enqueue_profile_review_notification on public.profiles;
create trigger enqueue_profile_review_notification
  after insert on public.profiles
  for each row execute function public.enqueue_admin_review_notification();

drop trigger if exists enqueue_listing_review_notification on public.listings;
create trigger enqueue_listing_review_notification
  after insert on public.listings
  for each row execute function public.enqueue_admin_review_notification();

drop trigger if exists enqueue_roommate_post_review_notification on public.roommate_posts;
create trigger enqueue_roommate_post_review_notification
  after insert on public.roommate_posts
  for each row execute function public.enqueue_admin_review_notification();

drop trigger if exists enqueue_message_report_review_notification on public.direct_message_reports;
create trigger enqueue_message_report_review_notification
  after insert on public.direct_message_reports
  for each row execute function public.enqueue_admin_review_notification();

drop trigger if exists mark_profile_review_notification_read on public.profiles;
create trigger mark_profile_review_notification_read
  after update of verification_status on public.profiles
  for each row
  when (old.verification_status = 'pending' and new.verification_status <> 'pending')
  execute function public.mark_admin_review_notification_reviewed();

drop trigger if exists mark_listing_review_notification_read on public.listings;
create trigger mark_listing_review_notification_read
  after update of moderation_status on public.listings
  for each row
  when (old.moderation_status = 'pending' and new.moderation_status <> 'pending')
  execute function public.mark_admin_review_notification_reviewed();

drop trigger if exists mark_roommate_post_review_notification_read on public.roommate_posts;
create trigger mark_roommate_post_review_notification_read
  after update of moderation_status on public.roommate_posts
  for each row
  when (old.moderation_status = 'pending' and new.moderation_status <> 'pending')
  execute function public.mark_admin_review_notification_reviewed();

drop trigger if exists mark_message_report_review_notification_read on public.direct_message_reports;
create trigger mark_message_report_review_notification_read
  after update of status on public.direct_message_reports
  for each row
  when (old.status = 'open' and new.status <> 'open')
  execute function public.mark_admin_review_notification_reviewed();

insert into public.admin_review_notifications (
  notification_key, title, detail, destination_tab, icon, source_type, source_id, created_at, read_at
)
select
  'profiles:' || profile.id::text,
  case
    when profile.verification_status <> 'pending'
      and upper(profile.role::text) in ('OWNER', 'LANDLORD') then 'Owner verification reviewed'
    when profile.verification_status <> 'pending' then 'User verification reviewed'
    when upper(profile.role::text) in ('OWNER', 'LANDLORD') then 'Owner verification needs review'
    else 'User verification needs review'
  end,
  coalesce(nullif(profile.full_name, ''), nullif(profile.email, ''), 'Name not provided'),
  'verifications',
  case when upper(profile.role::text) in ('OWNER', 'LANDLORD') then '🏠' else '👤' end,
  'profile',
  profile.id::text,
  profile.created_at,
  case
    when profile.verification_status = 'pending' then null
    else coalesce(profile.verified_at, profile.created_at)
  end
from public.profiles profile
where profile.verification_status = 'pending' or profile.verified_at is not null
on conflict (notification_key) do nothing;

insert into public.admin_review_notifications (
  notification_key, title, detail, destination_tab, icon, source_type, source_id, created_at, read_at
)
select
  'listings:' || listing.id::text,
  case when listing.moderation_status = 'pending'
    then 'Accommodation listing needs review'
    else 'Accommodation listing reviewed'
  end,
  coalesce(nullif(listing.title, ''), 'Untitled listing'),
  'listings',
  '🏢',
  'listing',
  listing.id::text,
  listing.created_at,
  case when listing.moderation_status = 'pending' then null else coalesce(listing.reviewed_at, listing.created_at) end
from public.listings listing
where listing.moderation_status = 'pending' or listing.reviewed_at is not null
on conflict (notification_key) do nothing;

insert into public.admin_review_notifications (
  notification_key, title, detail, destination_tab, icon, source_type, source_id, created_at, read_at
)
select
  'roommate_posts:' || post.id::text,
  case when post.moderation_status = 'pending'
    then 'Roommate post needs review'
    else 'Roommate post reviewed'
  end,
  coalesce(nullif(post.heading, ''), nullif(post.author_name, ''), 'Untitled post'),
  'roommates',
  '👥',
  'roommate_post',
  post.id::text,
  post.created_at,
  case when post.moderation_status = 'pending' then null else coalesce(post.reviewed_at, post.created_at) end
from public.roommate_posts post
where post.moderation_status = 'pending' or post.reviewed_at is not null
on conflict (notification_key) do nothing;

insert into public.admin_review_notifications (
  notification_key, title, detail, destination_tab, icon, source_type, source_id, created_at, read_at
)
select
  'direct_message_reports:' || report.id::text,
  case when report.status = 'open' then 'Flagged conversation report' else 'Conversation report reviewed' end,
  pg_catalog.format(
    '%s reported %s',
    coalesce(nullif(reporter.full_name, ''), 'BoardMate member'),
    coalesce(nullif(reported.full_name, ''), 'a user')
  ),
  'safety',
  '🛡️',
  'message_report',
  report.id::text,
  report.created_at,
  case when report.status = 'open' then null else coalesce(report.reviewed_at, report.created_at) end
from public.direct_message_reports report
left join public.profiles reporter on reporter.id = report.reporter_id
left join public.profiles reported on reported.id = report.reported_user_id
on conflict (notification_key) do nothing;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'admin_review_notifications'
    ) then
    alter publication supabase_realtime add table public.admin_review_notifications;
  end if;
end
$$;
